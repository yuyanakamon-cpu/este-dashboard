function getTimeContext(): string {
  const h = new Date().getHours()
  if (h >= 5  && h < 10) return '朝（5〜10時）: 出勤前のワクワク・ドキドキを伝える'
  if (h >= 10 && h < 13) return '昼（10〜13時）: ランチタイム、ビジネスマン層がスマホを見る'
  if (h >= 13 && h < 17) return '午後（13〜17時）: 人柄・日常系に最適。夕方予約へ繋げる一言を'
  if (h >= 17 && h < 22) return '夕方〜夜（17〜22時）★最重要: 仕事帰り層のピーク。予約誘導を積極的に'
  return '深夜（22〜5時）: 夜型層向け。落ち着いたトーン。明日の出勤予告も効果的'
}

function getDayContext(): string {
  const d = new Date().getDay()
  if (d === 5) return '金曜（予約最多）: 「今夜が狙い目」「今週最後」フレーズで全力訴求'
  if (d === 6) return '土曜: ゆっくりできる週末。リラックス訴求◎'
  if (d === 0) return '日曜: 「週の疲れを癒してから月曜へ」という訴求が刺さる'
  return `${'日月火水木金土'[d]}曜日（平日）: 仕事帰りの短時間利用を訴求`
}

